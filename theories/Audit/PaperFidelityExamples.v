(** Paper Example 2.3 is the guard against deleting the finite-generation
    premise from Remark 2.2.  Its open quadrant is contained in the rational
    cone generated by the strictly-positive integer period points. *)
Lemma paper_open_quadrant_in_positive_cone : forall point,
  closure_open_quadrant point -> Cone paper_positive_periodic point.
Proof.
  intros point [Hpoint0 Hpoint1].
  apply cleared_cone_gen.
  destruct (qvector_clear_denominators 2 (qvec_to_vector 2 point)) as
    [denominator [numerator [Hdenominator Hclear]]].
  exists denominator, numerator. repeat split; try assumption.
  - right. split.
    + assert (Hpositive :
          0 < q_of_nat denominator * point Fin.F1).
      { apply Qmult_lt_0_compat.
        - unfold q_of_nat, Qlt; cbn; lia.
        - exact Hpoint0. }
      setoid_rewrite <- (Hclear Fin.F1) in Hpositive.
      unfold Qlt, inject_Z in Hpositive; cbn in Hpositive; lia.
    + assert (Hpositive :
          0 < q_of_nat denominator * point (Fin.FS Fin.F1)).
      { apply Qmult_lt_0_compat.
        - unfold q_of_nat, Qlt; cbn; lia.
        - exact Hpoint1. }
      setoid_rewrite <- (Hclear (Fin.FS Fin.F1)) in Hpositive.
      unfold Qlt, inject_Z in Hpositive; cbn in Hpositive; lia.
  - intro index. unfold cleared_point, qvec_scale, qvec_to_vector.
    specialize (Hclear index). rewrite qvec_to_vector_nth in Hclear.
    setoid_rewrite Hclear.
    field. apply q_of_nat_nonzero. exact Hdenominator.
Qed.

Lemma paper_example_2_3_axis_in_closed_linearization :
  ClosedLinearization paper_positive_periodic (l0_z2 1 0).
Proof.
  split.
  - exists (l0_z2 2 1), (l0_z2 1 1). repeat split.
    + right. unfold l0_z2; cbn; lia.
    + right. unfold l0_z2; cbn; lia.
  - assert (Hboundary :
        QClosure (Cone paper_positive_periodic) (closure_q2 1 0)).
    { eapply qclosure_monotone with (left := closure_open_quadrant).
      - exact paper_open_quadrant_in_positive_cone.
      - exact closure_open_quadrant_boundary. }
    assert (Heq : QVecEq (zvec_to_qvec (l0_z2 1 0))
        (closure_q2 1 0)).
    { intro index. refine (Fin.caseS' index (fun index => _) _ _).
      * reflexivity.
      * intro tail. refine (Fin.caseS' tail (fun tail => _) _ _).
        -- reflexivity.
        -- intro impossible. inversion impossible. }
    apply (proj2 (qclosure_qvec_extensional 2
      (Cone paper_positive_periodic)
      (zvec_to_qvec (l0_z2 1 0)) (closure_q2 1 0) Heq)).
    exact Hboundary.
Qed.

Lemma paper_example_2_3_axis_not_member :
  ~ paper_positive_periodic (l0_z2 1 0).
Proof.
  unfold paper_positive_periodic, l0_z2; cbn; lia.
Qed.

Example paper_example_2_3_not_closed_linearization_fixed :
  FullPeriodic paper_positive_periodic /\
  ~ SameSet (ClosedLinearization paper_positive_periodic)
      paper_positive_periodic.
Proof.
  split; [exact paper_positive_full_periodic|].
  intro Hsame.
  apply paper_example_2_3_axis_not_member.
  apply (proj1 (Hsame (l0_z2 1 0))).
  exact paper_example_2_3_axis_in_closed_linearization.
Qed.

